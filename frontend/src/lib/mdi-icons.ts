export function resolveMdiIconName(
  markerIcon?: string,
  state?: HassEntity,
  registryEntry?: HassEntityRegistry,
  entityId?: string
): string {
  for (const candidate of [markerIcon, state?.attributes.icon, registryEntry?.icon]) {
    if (typeof candidate === "string" && candidate.trim()) return candidate.trim();
  }
  const domain = getEntityDomain(entityId ?? state?.entity_id ?? registryEntry?.entity_id ?? "");
  const cls = String(state?.attributes.device_class ?? "");
  const open = ["on", "open", "opening"].includes(state?.state ?? "");
  let icon = domainIcons.get(domain) ?? "help-circle";
  if (domain === "lock") icon = state?.state === "unlocked" ? "lock-open" : "lock";
  else if (domain === "light") icon = open ? "lightbulb-on" : "lightbulb";
  else if (domain === "cover" || domain === "binary_sensor") {
    if (cls === "garage" || cls === "garage_door") icon = open ? "garage-open" : "garage";
    else if (cls === "door" || cls === "opening") icon = open ? "door-open" : "door-closed";
    else if (cls === "window") icon = open ? "window-open-variant" : "window-closed-variant";
    else if (domain === "cover") icon = open ? "blinds-open" : "blinds";
    else icon = deviceIcons.get(cls) ?? icon;
  } else icon = deviceIcons.get(cls) ?? icon;
  return "mdi:" + icon;
}

function renderedPath(root: Element | ShadowRoot): string | null {
  const path = root.querySelector("svg path[d]")?.getAttribute("d");
  if (path) return path;
  for (const child of root.querySelectorAll("*")) {
    if (child.shadowRoot) {
      const nested = renderedPath(child.shadowRoot);
      if (nested) return nested;
    }
  }
  return null;
}

const pending = new Map<string, Promise<string | null>>();
async function loadIcon(name: string): Promise<string | null> {
  let icon: HTMLElement | undefined;
  try {
    if (!globalThis.customElements?.get("ha-icon") || !document.body) return null;
    icon = document.createElement("ha-icon");
    Object.assign(icon, { icon: "mdi:" + name });
    icon.style.cssText = "position:fixed;left:-10000px;pointer-events:none";
    icon.setAttribute("aria-hidden", "true");
    document.body.append(icon);
    for (let attempt = 0; attempt <= 20; attempt++) {
      const path = renderedPath(icon.shadowRoot ?? icon);
      if (path) {
        runtimePaths.set(name, path);
        return path;
      }
      if (attempt < 20) await new Promise((resolve) => setTimeout(resolve, 50));
    }
    return null;
  } catch {
    return null;
  } finally {
    icon?.remove();
  }
}
export async function resolveDynamicMdiPath(iconName: string): Promise<string | null> {
  const cached = getMdiIconPath(iconName);
  if (cached) return cached;
  const name = iconName.trim().replace(/^mdi:/, "");
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) return null;
  const existing = pending.get(name);
  if (existing) return existing;
  const promise = loadIcon(name).finally(() => pending.delete(name));
  pending.set(name, promise);
  return promise;
}
export function createMdiSvgDataUri(pathData: string, color: string): string {
  const escape = (s: string) =>
    s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="' +
    escape(color) +
    '" d="' +
    escape(pathData) +
    '"/></svg>';
  return "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg);
}
