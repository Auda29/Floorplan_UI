export type TranslationKey = keyof typeof en;
export type Localize = (key: TranslationKey, params?: TranslationParams) => string;

export function createLocalizer(language: string | undefined): Localize {
  const messages = language?.toLowerCase().startsWith("de") ? de : en;
  return (key, params = {}) => {
    let value: string = messages[key] ?? en[key] ?? String(key);
    for (const [name, replacement] of Object.entries(params)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
    return value;
  };
}
